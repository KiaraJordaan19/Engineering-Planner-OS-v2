/**
 * Marks_Intelligence_v1.4.0_Migration.gs — OPTIONAL, ONE-TIME, MANUAL migration.
 *
 * Do not run this automatically. Run it yourself from the Apps Script editor
 * (runMarksIntelligenceV140Migration) once. Depends on Migrations_Shared_v1.2.0.gs
 * (ensureColumn_ / migrationReport_) and on Marks_Intelligence_v1.3.1_Migration.gs
 * having been run first (this migration does not re-add its columns, and the
 * Faculty Rule Engine it plugs into is v1.3.1 work).
 *
 * Two independent changes bundled into one release because both were raised
 * together and both are scoped to "11 Marks Tracker" / "04 Module Rules":
 *
 *  1. AF ENGINE REWRITE — the "AF %" formula on "11 Marks Tracker" (a
 *     native spreadsheet formula, not code — never generated by any .gs
 *     file) previously averaged every module's AF Components entries MINUS
 *     a hardcoded "lowest 2 by rank" drop, applied identically to every
 *     module regardless of what "04 Module Rules" actually said. The "AF
 *     calculation method" column was pure documentation the formula never
 *     read. Per your framework review, no module's real rule count is
 *     confirmed (some frameworks don't state how many tests count), so a
 *     Best-N / drop-lowest-N automatic rule can't be built without
 *     inventing a number. This migration replaces the hardcoded formula
 *     with a plain average of whichever "10 AF Components" entries you've
 *     marked "Included in AF" (TRUE only when Written = TRUE and Excused =
 *     NOT TRUE) for that module — exclusion becomes your own per-test
 *     choice (mark a missed/void test Excused to drop it) instead of an
 *     automatic rank-based guess. Every module's "AF calculation method" /
 *     "Best-N rule" / "Drop-lowest rule" text on "04 Module Rules" is
 *     updated to describe this uniformly, including the two modules
 *     already Verified (Applied Mathematics B154, Engineering Mathematics
 *     145) — their old "Best 10" / "lowest 2 dropped" text described the
 *     retired mechanism and would otherwise now be inaccurate.
 *
 *  2. MODULE RULES DATA — sets AF/A1/A2 weighting and Rule status =
 *     Verified for Electrotechniques 143 and Computer Programming 143
 *     (currently "Missing rules"), and bumps Strength of Materials 143
 *     from "Partially verified" to "Verified" (its weightings were already
 *     entered). Values come directly from the module frameworks you
 *     supplied. Deliberately NOT touched, exactly as instructed — nothing
 *     here was confirmed by a framework and nothing here is invented:
 *       - Number of AF items
 *       - A2 subminimum / A3 subminimum
 *       - Min. main assessments required
 *     "Rounding rule" and "A3 calculation model" ARE set (Standard /
 *     Faculty FMp) since you gave those explicitly for every module.
 *
 *  3. "Published Final (After A3)" — one new column on "11 Marks Tracker",
 *     the mirror of v1.3.1's "Published Final (Before A3)" for the case
 *     where a module doesn't publish a raw A3 mark, only a new combined
 *     final percentage after A3. Wired into the Faculty Rule Engine by
 *     api_computeFacultyRuleEngine_ (API.js): the module's Official Final
 *     Mark becomes MAX(the normal FM1/FM2/FM3-based FMp, this entered
 *     value) — an A3 result (raw or published) can only ever raise your
 *     mark, never lower it, exactly like every other FMp route.
 *
 * Idempotent: safe to run more than once. The AF formula rewrite always
 * re-applies the current formula text (so re-running after a further
 * correction to this migration picks up the fix) but never touches any
 * other cell in the row; the Module Rules data write is also unconditional
 * for the 5 named module codes (this is deliberate, verified data entry
 * from you — not a guess this migration is protecting against re-running).
 * Nothing outside "11 Marks Tracker" / "10 AF Components" / "04 Module
 * Rules" is touched.
 */
function runMarksIntelligenceV140Migration() {
  var report = [];
  var ss = SpreadsheetApp.getActive();

  // ---- 1. AF engine: rewrite "AF %" formula on every Marks Tracker row ----
  var mtSheet = ss.getSheetByName(MARKS_TRACKER_SHEET);
  var afSheet = ss.getSheetByName(AF_COMPONENTS_SHEET);
  if (!mtSheet || !afSheet) {
    report.push('"' + MARKS_TRACKER_SHEET + '" or "' + AF_COMPONENTS_SHEET + '" sheet not found — skipped the AF formula rewrite.');
  } else {
    var pubFinalAfterResult = ensureColumn_(mtSheet, MARKS_TRACKER_HEADER_ROW, 'Published Final (After A3)');
    report.push(pubFinalAfterResult.added
      ? 'Added column to "' + MARKS_TRACKER_SHEET + '": "Published Final (After A3)" (left blank — enter only when your institution publishes a new combined final percentage after A3, instead of a raw A3 mark).'
      : 'Already present on "' + MARKS_TRACKER_SHEET + '": "Published Final (After A3)".');

    var mtMap = getColMap_(mtSheet, MARKS_TRACKER_HEADER_ROW);
    var afMap = getColMap_(afSheet, HEADER_ROW);
    var required = ['Module', 'AF %'];
    var missing = required.filter(function (h) { return !mtMap[h]; });
    var afRequired = ['Module', 'Percentage', 'Included in AF'];
    var afMissing = afRequired.filter(function (h) { return !afMap[h]; });
    if (missing.length || afMissing.length) {
      report.push('Could not rewrite the AF % formula — missing column(s): ' +
        missing.concat(afMissing).join(', ') + '.');
    } else {
      var afModuleCol = colLetter_(afMap['Module']);
      var afPctCol = colLetter_(afMap['Percentage']);
      var afIncludedCol = colLetter_(afMap['Included in AF']);
      var afFirstRow = HEADER_ROW + 1;
      var afLastRow = Math.max(afSheet.getLastRow(), afFirstRow + 200);
      var afModuleRange = "'" + AF_COMPONENTS_SHEET + "'!$" + afModuleCol + "$" + afFirstRow + ":$" + afModuleCol + "$" + afLastRow;
      var afPctRange = "'" + AF_COMPONENTS_SHEET + "'!$" + afPctCol + "$" + afFirstRow + ":$" + afPctCol + "$" + afLastRow;
      var afIncludedRange = "'" + AF_COMPONENTS_SHEET + "'!$" + afIncludedCol + "$" + afFirstRow + ":$" + afIncludedCol + "$" + afLastRow;

      var mtModuleCol = colLetter_(mtMap['Module']);
      var mtLastRow = mtSheet.getLastRow();
      var rewritten = 0;
      for (var row = MARKS_TRACKER_HEADER_ROW + 1; row <= mtLastRow; row++) {
        var moduleName = mtSheet.getRange(row, mtMap['Module']).getValue();
        if (!moduleName) continue;
        var moduleRef = "$" + mtModuleCol + row;
        var countExpr = "COUNTIFS(" + afModuleRange + "," + moduleRef + "," + afIncludedRange + ",TRUE())";
        var avgExpr = "AVERAGEIFS(" + afPctRange + "," + afModuleRange + "," + moduleRef + "," + afIncludedRange + ",TRUE())";
        var formula = "=IF(" + countExpr + "=0,\"No AF marks yet\"," + avgExpr + ")";
        mtSheet.getRange(row, mtMap['AF %']).setFormula(formula);
        rewritten++;
      }
      report.push('Rewrote the "AF %" formula on ' + rewritten + ' module row(s) in "' + MARKS_TRACKER_SHEET +
        '": now a plain average of "' + AF_COMPONENTS_SHEET + '" entries marked Included in AF = TRUE for that module ' +
        '(no more automatic "lowest 2 dropped" — mark a test Excused in "' + AF_COMPONENTS_SHEET + '" to exclude it instead).');
    }
  }

  // ---- 2. Module Rules data ----
  var mrSheet = ss.getSheetByName(MODULE_RULES_SHEET);
  if (!mrSheet) {
    report.push('"' + MODULE_RULES_SHEET + '" sheet not found — skipped Module Rules data entry.');
  } else {
    var mrMap = getColMap_(mrSheet, HEADER_ROW);
    var mrLastRow = mrSheet.getLastRow();
    var codeCol = mrMap['Module code'];
    var todayIso = Utilities.formatDate(new Date(), (Session.getScriptTimeZone() || 'Africa/Johannesburg'), 'yyyy-MM-dd');

    // Uniform AF-method text applied to every confirmed module below,
    // replacing whatever Best-N/drop-lowest description (or "UNKNOWN") it
    // had before -- the underlying formula is now the same for all of them.
    var afMethodText = 'Average of "10 AF Components" items marked Included in AF (manual — mark a test Written and not Excused to include it; mark it Excused to exclude it).';
    var bestNText = 'N/A — replaced by manual per-item inclusion (see "AF calculation method").';
    var dropLowestText = 'N/A — replaced by manual per-item inclusion (see "AF calculation method").';
    var roundingText = 'Standard (nearest whole %)';
    var a3ModelText = 'Best-combination per Faculty Rule Engine (FM1=AF+A1+A2, FM2=AF+A1+A3, FM3=AF+A2+A3, each renormalized; FMp = best available route).';

    var updates = [
      {
        code: '20753-154', name: 'Applied Mathematics B154',
        set: { 'AF calculation method': afMethodText, 'Best-N rule': bestNText, 'Drop-lowest rule': dropLowestText }
      },
      {
        code: '12599-143', name: 'Electrotechniques 143',
        set: {
          'Rule status': 'Verified', 'AF weighting': 0.15, 'A1 weighting': 0.35, 'A2 weighting': 0.5,
          'AF calculation method': afMethodText, 'Best-N rule': bestNText, 'Drop-lowest rule': dropLowestText,
          'Rounding rule': roundingText, 'A3 calculation model': a3ModelText,
          'A3 eligibility notes': 'A3 only if required.',
          'Rule source': 'Module framework', 'Last verified': todayIso,
          'General notes': 'Required A2 = (Target-0.15AF-0.35A1)/0.50.'
        }
      },
      {
        code: '38571-145', name: 'Engineering Mathematics 145',
        set: { 'AF calculation method': afMethodText, 'Best-N rule': bestNText, 'Drop-lowest rule': dropLowestText }
      },
      {
        code: '30317-143', name: 'Computer Programming 143',
        set: {
          'Rule status': 'Verified', 'AF weighting': 0.1, 'A1 weighting': 0.4, 'A2 weighting': 0.5,
          'AF calculation method': afMethodText, 'Best-N rule': bestNText, 'Drop-lowest rule': dropLowestText,
          'Rounding rule': roundingText, 'A3 calculation model': a3ModelText,
          'A3 eligibility notes': 'No A3 in framework shown.',
          'Rule source': 'Module framework', 'Last verified': todayIso,
          'General notes': 'Required A2 = (Target-0.10AF-0.40A1)/0.50.'
        }
      },
      {
        code: '19712-143', name: 'Strength of Materials 143',
        set: {
          'Rule status': 'Verified',
          'AF calculation method': afMethodText, 'Best-N rule': bestNText, 'Drop-lowest rule': dropLowestText,
          'Rounding rule': roundingText
        }
      }
    ];

    if (!codeCol) {
      report.push('"Module code" column not found on "' + MODULE_RULES_SHEET + '" — skipped Module Rules data entry.');
    } else {
      updates.forEach(function (u) {
        var targetRow = -1;
        for (var row = HEADER_ROW + 1; row <= mrLastRow; row++) {
          if (mrSheet.getRange(row, codeCol).getValue() === u.code) { targetRow = row; break; }
        }
        if (targetRow === -1) {
          report.push(u.name + ' (' + u.code + '): not found on "' + MODULE_RULES_SHEET + '" — skipped.');
          return;
        }
        var fieldsSet = [];
        Object.keys(u.set).forEach(function (header) {
          if (!mrMap[header]) { report.push(u.name + ': column "' + header + '" not found — skipped that field.'); return; }
          mrSheet.getRange(targetRow, mrMap[header]).setValue(u.set[header]);
          fieldsSet.push(header);
        });
        report.push(u.name + ' (' + u.code + '): set ' + fieldsSet.join(', ') + '.');
      });
    }
  }

  report.push('');
  report.push('Not touched: Number of AF items, A2 subminimum, A3 subminimum, Min. main assessments required — none of these were confirmed by a module framework, so none were invented.');
  report.push('Safe to run again at any time.');
  migrationReport_('Marks Intelligence v1.4.0 migration', report);
}

/** 1-based column index -> spreadsheet column letter(s) (1 -> "A", 27 -> "AA"). */
function colLetter_(col) {
  var letter = '';
  while (col > 0) {
    var rem = (col - 1) % 26;
    letter = String.fromCharCode(65 + rem) + letter;
    col = Math.floor((col - 1) / 26);
  }
  return letter;
}
